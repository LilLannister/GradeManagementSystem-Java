    private void AddButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_AddButtonActionPerformed
        try {
            if (SID.getText().isEmpty() || CID.getText().isEmpty() || TID.getText().isEmpty() || Grade.getText().isEmpty()) {
                JOptionPane.showMessageDialog(null, "Please fill all required fields! (Student ID, Course ID, Teacher ID, Grade)");
                return;
            }

            Float.parseFloat(Grade.getText());

            Class.forName("com.mysql.cj.jdbc.Driver");
            String database = "jdbc:mysql://localhost:3306/GradeManagement?user=root";
            Connection connect = DriverManager.getConnection(database);

            Statement state = connect.createStatement();

            String query = "INSERT INTO Grades(STID, CCode, TID, Grade) VALUES('%s', '%s', '%s', '%s')";
            query = String.format(query, SID.getText(), CID.getText(), TID.getText(), Grade.getText());

            state.execute(query);

            state.close();
            connect.close();

            JOptionPane.showMessageDialog(null, "Grade inserted successfully.");
            RefreshTable();

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(null, "Grade must be a number!");
        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(null, "Grade could not be inserted.");
        }
    }//GEN-LAST:event_AddButtonActionPerformed

    private void DeleteButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_DeleteButtonActionPerformed
        try {
            if (SID.getText().isEmpty() || CID.getText().isEmpty()) {
                JOptionPane.showMessageDialog(null, "Please enter Student ID and Course ID to delete.");
                return;
            }

            Class.forName("com.mysql.cj.jdbc.Driver");
            String database = "jdbc:mysql://localhost:3306/GradeManagement?user=root";
            Connection connect = DriverManager.getConnection(database);

            Statement state = connect.createStatement();

            String query = "DELETE FROM Grades WHERE STID='%s' AND CCode='%s'";
            query = String.format(query, SID.getText(), CID.getText());

            int deletedRows = state.executeUpdate(query);

            state.close();
            connect.close();

            if (deletedRows > 0) {
                JOptionPane.showMessageDialog(null, "Grade deleted successfully.");
                RefreshTable();
            } else {
                JOptionPane.showMessageDialog(null, "No grade record found for this student and course.");
            }

        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(null, "Grade could not be deleted.");
        }
    }//GEN-LAST:event_DeleteButtonActionPerformed

    private void SearchButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_SearchButtonActionPerformed
        try {
            if (SID.getText().isEmpty() || CID.getText().isEmpty()) {
                JOptionPane.showMessageDialog(null, "Please enter Student ID and Course ID to search.");
                return;
            }

            Class.forName("com.mysql.cj.jdbc.Driver");
            String database = "jdbc:mysql://localhost:3306/GradeManagement?user=root";
            Connection connect = DriverManager.getConnection(database);

            Statement state = connect.createStatement();

            String query = "SELECT * FROM Grades WHERE STID='%s' AND CCode='%s'";
            query = String.format(query, SID.getText(), CID.getText());

            ResultSet result = state.executeQuery(query);

            if (result.next()) {
                SID.setText(result.getString("STID"));
                CID.setText(result.getString("CCode"));
                TID.setText(result.getString("TID"));
                Grade.setText(result.getString("Grade"));

                JOptionPane.showMessageDialog(null, "Grade record found.");
            } else {
                JOptionPane.showMessageDialog(null, "No grade record found for this student and course.");
            }

            state.close();
            connect.close();

        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(null, "Grade could not be searched.");
        }
    }//GEN-LAST:event_SearchButtonActionPerformed

