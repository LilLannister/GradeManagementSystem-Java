private void RefreshTable() {
    try {
        Class.forName("com.mysql.cj.jdbc.Driver");
        String database = "jdbc:mysql://localhost:3306/GradeManagement?user=root";
        Connection connect = DriverManager.getConnection(database);

        Statement state = connect.createStatement();

        String query = "SELECT * FROM Grades";
        ResultSet result = state.executeQuery(query);

        DefaultTableModel dm = (DefaultTableModel) Table1.getModel();

        int rowCount = dm.getRowCount();
        for (int i = rowCount - 1; i >= 0; i--) {
            dm.removeRow(i);
        }

        while (result.next()) {
            String studentID = result.getString("STID");
            String courseCode = result.getString("CCode");
            String teacherID = result.getString("TID");
            String grade = result.getString("Grade");

            Object[] row = {studentID, courseCode, teacherID, grade};
            dm.addRow(row);
        }

        state.close();
        connect.close();

    } catch (Exception e) {
        e.printStackTrace();
        JOptionPane.showMessageDialog(null, "Database Error!");
    }
}
